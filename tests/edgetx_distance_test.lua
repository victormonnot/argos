test("every stick amplitude temporarily releases only its own axis",function()
  for _,axis in ipairs({"rud","ele"}) do
    for _,amplitude in ipairs({103,257,513,1024,-1024}) do
      local r=active(); local initial=r:latestStatus()
      local phase=axis == "rud" and "yawPhase" or "pitchPhase"
      local output=axis == "rud" and 1 or 5
      local other=axis == "rud" and 5 or 1
      r[axis]=amplitude
      local hb=r.output[4]
      for i=1,30 do
        r:set(i+1,80,true,i*10,nil,30,true)
        eq(r:latestStatus().state,"A"); eq(r:latestStatus()[phase],"M")
        eq(r.output[output],0); eq(r.output[output+1],0)
        eq(r.output[other],axis == "rud" and 30 or 80)
        eq(r.output[other+1],1024)
        eq(r.output[4],-hb); hb=r.output[4]
        eq(r:latestStatus().generation,initial.generation)
        eq(r:latestStatus().session,initial.session)
      end
      r[axis]=0; r:set(32,80,true,310,nil,30,true)
      r:set(33,80,true,320,nil,30,true)
      local old=r:latestStatus(); r:set(34,80,true,330,old,30,true)
      eq(r:latestStatus()[phase],"R"); eq(r.output[output+1],0)
      r:set(35,80,true,331,nil,30,true)
      eq(r:latestStatus()[phase],"A"); eq(r.output[output+1],1024)
      eq(r:latestStatus().generation,initial.generation)
    end
  end
end)
