test("recenter barrier compares signed clock wrap with integer arithmetic",function()
  local base=2147483630
  local function at(delta)
    local n=base+delta
    if n>2147483647 then n=n-2147483647-2147483647-2 end
    return n
  end
  local r=radio({now=base}); r:begin(); r:arm("D"); r:set(1,80,true,nil,nil,30,true)
  r.ele=150; r:set(2,60,true,at(5),nil,40,true)
  r.ele=0; r:set(3,60,true,at(10),nil,40,true)
  r:set(4,60,true,at(20),nil,40,true); local old=r:latestStatus()
  r:set(5,60,true,at(30),old,40,true)
  eq(r:latestStatus().pitchPhase,"R"); eq(r.output[6],0)
  r:set(6,60,true,at(31),old,40,true); eq(r.output[6],0)
  r:set(7,60,true,at(32),nil,40,true)
  eq(r.output[5],40); eq(r:latestStatus().pitchPhase,"A")
end)


